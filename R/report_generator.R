# report_generator.R
# 基于 snapshots.rds 和 figures/ 生成 LaTeX 文章

library(knitr)
library(dplyr)

#' 生成 LaTeX 报告
#' @param package_dir 素材包根目录（包含 snapshots.rds 和 figures/）
#' @param output_file 输出 .tex 文件路径，默认为 package_dir/updated_article.tex
#' @param template 可选，自定义 LaTeX 模板路径
generate_latex_report <- function(package_dir,
                                  output_file = file.path(package_dir, "updated_article.tex"),
                                  template = NULL) {

  # 读取快照数据
  snaps <- readRDS(file.path(package_dir, "snapshots.rds"))

  # 准备 LaTeX 头部
  latex_head <- c(
    "\\documentclass{article}",
    "\\usepackage{graphicx}",
    "\\usepackage{booktabs}",
    "\\usepackage{float}",
    "\\usepackage{soul}",
    "\\usepackage{hyperref}",
    "\\usepackage[margin=1in]{geometry}",
    "\\title{Updated Meta-Analysis Report: Perioperative Immunotherapy in Resectable NSCLC}",
    "\\author{Generated by AIMetaAnalysis}",
    "\\date{\\today}",
    "\\begin{document}",
    "\\maketitle",
    "\\section{Results}",
    ""
  )

  latex_body <- c()

  for (i in seq_along(snaps)) {
    s <- snaps[[i]]

    # 图形插入（使用相对路径 figures/）
    fig_path <- file.path("figures", s$figure_file)
    latex_body <- c(latex_body,
                    paste0("\\begin{figure}[H]"),
                    "  \\centering",
                    paste0("  \\includegraphics[width=\\textwidth]{", fig_path, "}"),
                    paste0("  \\caption{", s$caption, "}"),
                    paste0("  \\label{fig:", s$id, "}"),
                    "\\end{figure}",
                    ""
    )

    # 统计摘要
    eff <- s$pooled_effect
    hetero <- s$heterogeneity

    # 正确处理 p 值：数学环境内不含句点
    p_val_text <- if (eff$pval < 0.001) {
      "$p < 0.001$"
    } else {
      paste0("$p = ", round(eff$pval, 3), "$")
    }
    hetero_p_text <- paste0("$p = ", round(hetero$Q_pval, 3), "$")

    summary_text <- paste0(
      "\\noindent\\textbf{Pooled effect (", s$model, " effects):} ",
      eff$measure, " = ", round(eff$value, 2),
      " (95\\% CI: ", round(eff$lower, 2), "--", round(eff$upper, 2),
      "), ", p_val_text, ". ",
      "Heterogeneity: $I^2$ = ", round(hetero$I2, 1), "\\%, ",
      "$\\tau^2$ = ", round(hetero$tau2, 3), ", ",
      "$Q$ = ", round(hetero$Q, 2), " (df = ", hetero$Q_df, "), ", hetero_p_text, "."
    )
    latex_body <- c(latex_body, summary_text, "")

    # Insights 高亮（若存在）
    if (!is.null(s$user_insights) && nchar(trimws(s$user_insights)) > 0) {
      latex_body <- c(latex_body,
                      paste0("\\noindent\\textbf{Insights:} \\hl{", s$user_insights, "}"),
                      ""
      )
    }
    latex_body <- c(latex_body, "\\medskip", "")
  }

  # 尾部
  latex_tail <- c(
    "\\section{Discussion}",
    "This report was automatically generated based on user-captured snapshots from the AIMetaAnalysis Shiny application. Differences from the original publication are highlighted where noted.",
    "",
    "\\end{document}"
  )

  # 合并并写入文件
  full_latex <- c(latex_head, latex_body, latex_tail)
  writeLines(full_latex, output_file)

  message("LaTeX report written to: ", output_file)
  return(invisible(output_file))
}

